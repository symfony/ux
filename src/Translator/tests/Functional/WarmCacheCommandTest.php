namespace Symfony\UX\Translator\Tests\Functional;

use PHPUnit\Framework\TestCase;
use Symfony\Bundle\FrameworkBundle\Console\Application;
use Symfony\Component\Console\Tester\CommandTester;
use Symfony\Component\Filesystem\Filesystem;
use Symfony\UX\Translator\Tests\Kernel\StableCacheDirAppKernel;

final class WarmCacheCommandTest extends TestCase
{
    private string $tmpDir;

    protected function setUp(): void
    {
        $this->tmpDir = sys_get_temp_dir().'/translator_bundle/'.uniqid('warm_cache_', true);
    }

    protected function tearDown(): void
    {
        new Filesystem()->remove($this->tmpDir);
    }

    public function testDumpsTranslationsWhenTheContainerIsAlreadyBuilt(): void
    {
        new StableCacheDirAppKernel($this->tmpDir)->boot();

        $kernel = new StableCacheDirAppKernel($this->tmpDir);
        // Building the container dumped the translations, the command must dump them again
        new Filesystem()->remove($kernel->getDumpDir());
        $application = new Application($kernel);
        $tester = new CommandTester($application->find('ux:translator:warm-cache'));

        $tester->execute([]);

        $tester->assertCommandIsSuccessful();
        $this->assertStringEqualsFile(
            $kernel->getDumpDir().'/index.js',
            <<<'JS'
                // This file is auto-generated by the Symfony UX Translator. Do not edit it manually.

                export const localeFallbacks = {"en":null,"fr":"en"};
                export const defaultLocale = "fr";
                export const messages = {
                    "symfony_ux.great": {"translations":{"messages":{"en":"Symfony UX is awesome","fr":"Symfony UX est g\u00e9nial"}}},
                };

                JS
        );
    }
}
